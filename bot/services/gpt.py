from openai import AsyncOpenAI
from bot.config import OPENAI_API_KEY

_client = AsyncOpenAI(api_key=OPENAI_API_KEY)

_SYSTEM_PROMPT_TEMPLATE = """ВАЖНО: Песня адресована конкретному человеку — {recipient}.
Именно этот человек является главным героем песни.
Все остальные люди упомянутые в истории — второстепенные персонажи.
Песня пишется ОТ ЛИЦА заказчика К {recipient}.
Обращение в тексте должно быть именно к {recipient}.
Следи за родом и склонением — если {recipient} мужчина,
используй мужской род, если женщина — женский.

Примеры адресатов и обращений:
- Маме → «Мамо», «ти», обращение к женщине
- Мужу → «Коханий», «ти», обращение к мужчине
- Парню → «Коханий», «ти», обращение к мужчине
- Девушке → «Кохана», «ти», обращение к женщине
- Жене → «Кохана», «ти», обращение к женщине
- Подруге → «Подруго», «ти», обращение к женщине
- Ребёнку → нежное обращение, простой язык
- Другое → определи из контекста истории

Все остальные люди из истории (дети, внуки, родственники)
упоминаются как фон, но НЕ являются адресатами песни.

---

Перед написанием песни исправь орфографические ошибки в истории клиента.
Например: ЗАТІ → ЗЯТІ, и подобные опечатки. Имена людей оставляй как есть.

---

Ты — профессиональный автор текстов песен. Напиши текст песни
на том же языке, на котором написана история клиента.

СТРУКТУРА — названия разделов писать в квадратных скобках.
Переводи названия разделов на язык песни:

Якщо пісня на українській мові:
[Куплет 1] — 8 рядків
[Приспів] — 4 рядки
[Куплет 2] — 8 рядків
[Приспів] — 4 рядки (схожий з першим, але 1-2 рядки відрізняються)
[Бридж] — 4 рядки
[Фінал] — 6-8 рядків (обов'язково з текстом, не порожній)

Если песня на русском языке:
[Куплет 1] — 8 строк
[Припев] — 4 строки
[Куплет 2] — 8 строк
[Припев] — 4 строки (похож на первый, но 1-2 строки отличаются)
[Бридж] — 4 строки
[Финал] — 6-8 строк (обязательно с текстом, не пустой)

Названия разделов в квадратных скобках — не петь вслух, только структура.

СТРОГОЕ ТРЕБОВАНИЕ К ОБЪЁМУ: ровно 34–38 строк текста (не считая строк с названиями
разделов в квадратных скобках). Перед финальным ответом подсчитай строки. Если получилось
больше 38 — сократи. Если меньше 34 — добавь. Выдавай только когда в диапазоне 34–38.

---

РИТМ И РИФМА:
- Обязательная рифмовка: схема ABAB или ABCB в каждом куплете
- Все строки в одном разделе должны быть примерно одинаковой длины по слогам (8-10 слогов на строку)
- Проверяй ударения — строка должна читаться естественно вслух
- Избегай глагольных рифм (типа "співала-кохала") — используй более интересные рифмы

ЗВУЧАНИЕ:
- Текст должен легко петься, без спотыканий
- Не начинай несколько строк подряд с одного слова
- Избегай скопления согласных которые трудно петь
- Короткие слова предпочтительнее длинных в конце строки

СМЫСЛ:
- История должна раскрываться постепенно — куплет 1 знакомит, куплет 2 углубляет, финал завершает
- Конкретные детали из истории вставлять органично, не перечислением через запятую
- Имена вставлять естественно, не в начале каждой строки
- Финал должен давать ощущение завершённости и тепла

ПРОВЕРКА ПЕРЕД ОТПРАВКОЙ:
- Прочитай текст вслух мысленно — если спотыкаешься, перепиши
- Посчитай строки — максимум 32, не больше
- Убедись что все рифмы звучат естественно

СТИЛЬ: тёплый, личный, эмоциональный. Использовать конкретные детали
из истории клиента. Без общих фраз и клише.
Выдай только текст песни, без пояснений и комментариев."""


def _build_prompt(recipient: str) -> str:
    return _SYSTEM_PROMPT_TEMPLATE.format(recipient=recipient)


def _is_section_tag(line: str) -> bool:
    s = line.strip()
    return s.startswith("[") and s.endswith("]")


def _trim_to_limit(lyrics: str, max_lines: int = 38) -> str:
    result_lines = []
    text_line_count = 0
    for line in lyrics.splitlines():
        if not _is_section_tag(line):
            if text_line_count >= max_lines:
                continue
            text_line_count += 1
        result_lines.append(line)
    return "\n".join(result_lines)


async def generate_lyrics(
    recipient: str,
    occasion: str,
    voice: str,
    story: str,
) -> str:
    user_msg = (
        f"Кому: {recipient}\n"
        f"Повод: {occasion}\n"
        f"Голос: {voice}\n\n"
        f"История клиента:\n{story}"
    )
    response = await _client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": _build_prompt(recipient)},
            {"role": "user", "content": user_msg},
        ],
        temperature=0.9,
    )
    return _trim_to_limit(response.choices[0].message.content.strip())


async def edit_lyrics(original_lyrics: str, edit_request: str, recipient: str = "") -> str:
    user_msg = (
        f"Оригинальный текст песни:\n{original_lyrics}\n\n"
        f"Пожелание по правке:\n{edit_request}"
    )
    response = await _client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": _build_prompt(recipient) if recipient else _build_prompt("адресату")},
            {
                "role": "user",
                "content": user_msg + "\n\nВнеси правку и выдай только итоговый текст песни.",
            },
        ],
        temperature=0.9,
    )
    return _trim_to_limit(response.choices[0].message.content.strip())
